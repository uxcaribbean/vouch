alter table public.regions enable row level security;
alter table public.trades enable row level security;

create policy "regions are public" on public.regions
  for select using (true);

create policy "trades are public" on public.trades
  for select using (true);

-- New tables are NOT auto-exposed to API roles (post-2026 Supabase default),
-- so every migration grants explicitly. Writes to taxonomy are edge-function
-- (service role) territory only.
grant select on public.regions to anon, authenticated;
grant select on public.trades to anon, authenticated;
grant all on public.regions, public.trades to service_role;
grant usage, select on all sequences in schema public to service_role;
