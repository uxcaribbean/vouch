-- ---------------------------------------------------------------------------
-- trades: seeded taxonomy + user-proposed entries (M2) + admin merge (M9).
-- keywords feed search synonyms ("ac" → AC Technician) per M3.
-- Seeded ids start at 100; proposed trades get ids from this sequence too.
-- ---------------------------------------------------------------------------
create table public.trades (
  id int generated by default as identity (start with 1000) primary key,
  slug text unique not null,
  name text not null,
  category text not null,
  keywords text[] not null default '{}',
  status text not null default 'active'
    check (status in ('active', 'proposed', 'merged')),
  merged_into_id int references public.trades (id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create trigger trades_updated_at
  before update on public.trades
  for each row execute function public.set_updated_at();

